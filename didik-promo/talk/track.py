"""Turns hands.json into smooth paths for Yul's two hands during "macam ni": HAND (his watch hand, on the
left of the frame) and HAND2 (the window-side hand, on the right). Each is seeded at a frame where it is
clearly up and followed frame to frame by the nearest detection; a detection already taken by the other hand
is skipped, jumps are ignored, gaps are interpolated, and the result is smoothed.

    python track.py hands.json T1 X1 Y1 T2 X2 Y2 ../remotion/talk-hands.ts
"""
import json
import sys

import numpy as np

src = sys.argv[1]
seeds = [tuple(map(float, sys.argv[2:5])), tuple(map(float, sys.argv[5:8]))]
out = sys.argv[8]
d = json.load(open(src))
frames = d["frames"]
n = len(frames)
MAX_JUMP = 230  # px per frame; more than this is the other hand


def track(seed_t, sx, sy, taken):
    pts = [None] * n
    seed = round((seed_t - d["start"]) * d["fps"])

    def follow(order, start_xy):
        last, gap = start_xy, 0
        for i in order:
            cands = [h for h in frames[i]["hands"] if (h["x"], h["y"]) != taken[i]]
            best = min(cands, key=lambda h: (h["x"] - last[0]) ** 2 + (h["y"] - last[1]) ** 2, default=None)
            if best is not None and np.hypot(best["x"] - last[0], best["y"] - last[1]) <= MAX_JUMP * (gap + 1):
                pts[i] = (best["x"], best["y"])
                last, gap = pts[i], 0
            else:
                gap += 1

    follow(range(seed, n), (sx, sy))
    follow(range(seed - 1, -1, -1), pts[seed] or (sx, sy))
    return pts


def smooth(pts):
    known = [i for i in range(n) if pts[i] is not None]
    xs = np.interp(range(n), known, [pts[i][0] for i in known])
    ys = np.interp(range(n), known, [pts[i][1] for i in known])
    k = np.array([1, 2, 3, 2, 1], float)
    k /= k.sum()
    xs = np.convolve(np.pad(xs, 2, mode="edge"), k, "valid")
    ys = np.convolve(np.pad(ys, 2, mode="edge"), k, "valid")
    return [[round(x), round(y)] for x, y in zip(xs, ys)], len(known)


a = track(*seeds[0], [None] * n)
b = track(*seeds[1], a)
pa, ka = smooth(a)
pb, kb = smooth(b)
with open(out, "w") as f:
    f.write("// Generated by talk/track.py from MediaPipe hand tracking: Yul's two hands (palm centres),\n")
    f.write("// one [x, y] per frame from HAND_START, in 1080×1920 pixels of the unscaled video.\n")
    f.write(f"export const HAND_START = {d['start']};\n")
    f.write("export const HAND: Array<[number, number]> = " + json.dumps(pa) + "; // watch hand (left of frame)\n")
    f.write("export const HAND2: Array<[number, number]> = " + json.dumps(pb) + "; // window-side hand (right of frame)\n")
print(f"watch hand {ka}/{n}, window hand {kb}/{n} frames tracked")
for i in range(0, n, 9):
    print(f"{d['start'] + i / 30:.2f}  watch {tuple(pa[i])}{'' if a[i] else '*'}   window {tuple(pb[i])}{'' if b[i] else '*'}")
